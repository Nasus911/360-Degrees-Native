do $$
begin
  create type public.order_status as enum ('new', 'preparing', 'ready_for_pickup', 'completed', 'cancelled');
exception
  when duplicate_object then null;
end $$;

do $$
begin
  create type public.order_channel as enum ('online', 'counter');
exception
