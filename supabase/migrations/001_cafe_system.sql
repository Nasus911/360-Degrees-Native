create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    new.email,
    'customer'
  );
  return new;
end;
$$;

create or replace function public.notify_order_ready()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'ready_for_pickup' and old.status is distinct from new.status and new.customer_id is not null then
    insert into public.notifications (user_id, order_id, title, message)
    values (new.customer_id, new.id, 'Your order is ready for pickup', 'Your order is ready at Lipa Branch.');
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

drop trigger if exists on_order_ready on public.orders;
create trigger on_order_ready
  after update of status on public.orders
  for each row execute procedure public.notify_order_ready();

