-- Preserve the earlier prototype tables, whose columns are incompatible with
-- the production schema below. The original rows remain available in the
-- legacy_* tables.
do $$
begin
  if to_regclass('public.branches') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'branches' and column_name = 'id'
     ) then
    execute 'alter table public.branches rename to legacy_branches';
  end if;
  if to_regclass('public.inventory') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'inventory' and column_name = 'sku'
     ) then
    execute 'alter table public.inventory rename to legacy_inventory';
  end if;
  if to_regclass('public.menu_items') is not null then
    execute 'alter table public.menu_items rename to legacy_menu_items';
  end if;
  if to_regclass('public.profiles') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public' and table_name = 'profiles' and column_name = 'full_name'
     ) then
    execute 'alter table public.profiles rename to legacy_profiles';
  end if;
end $$;

